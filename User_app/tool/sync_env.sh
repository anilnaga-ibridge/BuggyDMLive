#!/usr/bin/env bash
# ==============================================================================
# Buggy User App - Environment Sync Script
# Syncs secrets from User_app/.env into platform-specific gitignored config files
# Usage: ./tool/sync_env.sh [apply|restore-placeholders]
# ==============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
ENV_FILE="$APP_DIR/.env"

ACTION="${1:-apply}"

if [ ! -f "$ENV_FILE" ]; then
  echo "Error: .env file not found at $ENV_FILE"
  echo "Copy .env.example to .env and configure your keys first."
  exit 1
fi

# Load variables from .env
eval "$(grep -E '^(GOOGLE_MAPS_|FIREBASE_|GOOGLE_SERVER_CLIENT_ID|FACEBOOK_)' "$ENV_FILE" | sed 's/^[[:space:]]*//')"

if [ "$ACTION" = "restore-placeholders" ]; then
  echo "Restoring placeholder values in tracked template files..."
  sed -i '' 's/<string>AIzaSy[^<]*<\/string>/<string>YOUR_FIREBASE_IOS_API_KEY<\/string>/g' "$APP_DIR/ios/GoogleService-Info.plist" 2>/dev/null || true
  sed -i '' 's/"current_key": "AIzaSy[^"]*"/"current_key": "YOUR_FIREBASE_ANDROID_API_KEY"/g' "$APP_DIR/android/app/google-services.json" 2>/dev/null || true
  echo "Placeholders restored."
  exit 0
fi

echo "Applying environment configuration from .env..."

# 1. Update web/env.js (gitignored)
cat > "$APP_DIR/web/env.js" <<EOF
// Auto-generated by tool/sync_env.sh from .env - do NOT commit
window.ENV = window.ENV || {};

window.ENV.GOOGLE_MAPS_WEB_API_KEY = "${GOOGLE_MAPS_WEB_API_KEY}";
window.ENV.GOOGLE_SERVER_CLIENT_ID = "${GOOGLE_SERVER_CLIENT_ID}";

window.ENV.FIREBASE_CONFIG = {
  apiKey: "${FIREBASE_WEB_API_KEY}",
  authDomain: "${FIREBASE_WEB_AUTH_DOMAIN}",
  projectId: "${FIREBASE_PROJECT_ID}",
  storageBucket: "${FIREBASE_STORAGE_BUCKET}",
  messagingSenderId: "${FIREBASE_MESSAGING_SENDER_ID}",
  appId: "${FIREBASE_WEB_APP_ID}"
};

if (typeof self !== 'undefined') {
  self.ENV = window.ENV;
}
EOF
echo " -> Updated web/env.js"

# 2. Update ios/Flutter/Env.xcconfig (gitignored)
cat > "$APP_DIR/ios/Flutter/Env.xcconfig" <<EOF
// Auto-generated by tool/sync_env.sh from .env - do NOT commit
GOOGLE_MAPS_IOS_API_KEY = ${GOOGLE_MAPS_IOS_API_KEY}
EOF
echo " -> Updated ios/Flutter/Env.xcconfig"

# 3. Update android/local.properties (gitignored)
if [ -f "$APP_DIR/android/local.properties" ]; then
  if grep -q "^maps.apiKey=" "$APP_DIR/android/local.properties"; then
    sed -i '' "s|^maps.apiKey=.*|maps.apiKey=${GOOGLE_MAPS_ANDROID_API_KEY}|" "$APP_DIR/android/local.properties"
  else
    echo "maps.apiKey=${GOOGLE_MAPS_ANDROID_API_KEY}" >> "$APP_DIR/android/local.properties"
  fi
  echo " -> Updated android/local.properties"
fi

echo "All environment configurations synced successfully."
